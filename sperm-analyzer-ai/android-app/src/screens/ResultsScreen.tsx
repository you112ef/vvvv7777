/**
 * Results Screen - Display analysis results with charts
 */

import React, { useState, useEffect } from 'react';
import {
  View,
  ScrollView,
  StyleSheet,
  Dimensions,
  Alert,
} from 'react-native';
import {
  Text,
  Card,
  Button,
  Divider,
  Surface,
  Chip,
} from 'react-native-paper';
import { useTranslation } from 'react-i18next';
import Icon from 'react-native-vector-icons/MaterialIcons';
import {
  LineChart,
  BarChart,
  PieChart,
  ProgressChart,
} from 'react-native-chart-kit';
import Share from 'react-native-share';

import { AnalysisResult } from '../services/AIProcessor';
import { colors, spacing, typography, shadows } from '../styles/theme';

const { width } = Dimensions.get('window');
const chartWidth = width - spacing.lg * 2;

interface ResultsScreenProps {
  route?: {
    params?: {
      analysisResult: AnalysisResult;
    };
  };
}

const ResultsScreen: React.FC<ResultsScreenProps> = ({ route }) => {
  const { t } = useTranslation();
  const [selectedTab, setSelectedTab] = useState<'overview' | 'casa' | 'charts'>('overview');
  const [analysisResult, setAnalysisResult] = useState<AnalysisResult | null>(
    route?.params?.analysisResult || null
  );

  // Mock data if no real result is provided
  useEffect(() => {
    if (!analysisResult) {
      // Generate mock data for demonstration
      const mockResult: AnalysisResult = {
        type: 'video',
        sperm_count: 45,
        motility_parameters: {
          total_count: 45,
          motile_count: 32,
          progressive_count: 18,
          non_progressive_count: 14,
          immotile_count: 13,
          motility_percentage: 71.1,
          progressive_motility_percentage: 40.0,
          average_vcl: 65.2,
          average_vsl: 42.8,
          average_vap: 58.1,
          average_lin: 65.6,
          average_alh: 4.2,
          average_bcf: 8.5,
        },
        casa_metrics: [],
        processing_time: 12500,
        timestamp: Date.now(),
      };
      setAnalysisResult(mockResult);
    }
  }, []);

  const shareResults = async () => {
    if (!analysisResult) return;

    const shareText = `Sperm Analysis Results:
Total Count: ${analysisResult.sperm_count}
Motility: ${analysisResult.motility_parameters?.motility_percentage.toFixed(1)}%
Progressive: ${analysisResult.motility_parameters?.progressive_motility_percentage.toFixed(1)}%
Average VCL: ${analysisResult.motility_parameters?.average_vcl.toFixed(1)} μm/s

Generated by Sperm Analyzer AI`;

    try {
      await Share.open({
        message: shareText,
        title: 'Sperm Analysis Results',
      });
    } catch (error) {
      console.log('Share cancelled');
    }
  };

  const exportToPDF = () => {
    Alert.alert(
      'Export Results',
      'PDF export functionality will be implemented in the next version.',
      [{ text: 'OK' }]
    );
  };

  if (!analysisResult) {
    return (
      <View style={styles.emptyContainer}>
        <Icon name="assessment" size={64} color={colors.textSecondary} />
        <Text style={styles.emptyTitle}>{t('noResults')}</Text>
        <Text style={styles.emptySubtitle}>
          Analyze some media to see results here
        </Text>
      </View>
    );
  }

  const renderOverviewTab = () => {
    const motility = analysisResult.motility_parameters;
    if (!motility) return null;

    const overviewCards = [
      {
        title: 'Total Count',
        value: analysisResult.sperm_count.toString(),
        unit: 'sperm',
        icon: 'visibility',
        color: colors.primary,
      },
      {
        title: 'Motility',
        value: motility.motility_percentage.toFixed(1),
        unit: '%',
        icon: 'trending-up',
        color: colors.success,
      },
      {
        title: 'Progressive',
        value: motility.progressive_motility_percentage.toFixed(1),
        unit: '%',
        icon: 'arrow-forward',
        color: colors.info,
      },
      {
        title: 'Concentration',
        value: (analysisResult.sperm_count * 1000000 / 10).toFixed(0), // Mock calculation
        unit: '/ml',
        icon: 'scatter-plot',
        color: colors.accent,
      },
    ];

    return (
      <ScrollView showsVerticalScrollIndicator={false}>
        {/* Overview Cards */}
        <View style={styles.cardsGrid}>
          {overviewCards.map((card, index) => (
            <Card key={index} style={styles.overviewCard}>
              <Card.Content style={styles.overviewCardContent}>
                <View style={[styles.cardIcon, { backgroundColor: card.color }]}>
                  <Icon name={card.icon} size={24} color="white" />
                </View>
                <Text style={styles.cardValue}>
                  {card.value}
                  <Text style={styles.cardUnit}> {card.unit}</Text>
                </Text>
                <Text style={styles.cardTitle}>{card.title}</Text>
              </Card.Content>
            </Card>
          ))}
        </View>

        {/* Motility Breakdown */}
        <Card style={styles.sectionCard}>
          <Card.Content>
            <Text style={styles.cardSectionTitle}>Motility Breakdown</Text>
            <View style={styles.motilityItem}>
              <Text style={styles.motilityLabel}>Progressive</Text>
              <View style={styles.motilityBar}>
                <View
                  style={[
                    styles.motilityProgress,
                    {
                      width: `${motility.progressive_motility_percentage}%`,
                      backgroundColor: colors.success,
                    },
                  ]}
                />
              </View>
              <Text style={styles.motilityValue}>
                {motility.progressive_count} ({motility.progressive_motility_percentage.toFixed(1)}%)
              </Text>
            </View>
            <View style={styles.motilityItem}>
              <Text style={styles.motilityLabel}>Non-Progressive</Text>
              <View style={styles.motilityBar}>
                <View
                  style={[
                    styles.motilityProgress,
                    {
                      width: `${(motility.non_progressive_count / motility.total_count) * 100}%`,
                      backgroundColor: colors.warning,
                    },
                  ]}
                />
              </View>
              <Text style={styles.motilityValue}>
                {motility.non_progressive_count} ({((motility.non_progressive_count / motility.total_count) * 100).toFixed(1)}%)
              </Text>
            </View>
            <View style={styles.motilityItem}>
              <Text style={styles.motilityLabel}>Immotile</Text>
              <View style={styles.motilityBar}>
                <View
                  style={[
                    styles.motilityProgress,
                    {
                      width: `${(motility.immotile_count / motility.total_count) * 100}%`,
                      backgroundColor: colors.error,
                    },
                  ]}
                />
              </View>
              <Text style={styles.motilityValue}>
                {motility.immotile_count} ({((motility.immotile_count / motility.total_count) * 100).toFixed(1)}%)
              </Text>
            </View>
          </Card.Content>
        </Card>

        {/* Analysis Info */}
        <Card style={styles.sectionCard}>
          <Card.Content>
            <Text style={styles.cardSectionTitle}>Analysis Information</Text>
            <View style={styles.infoRow}>
              <Text style={styles.infoLabel}>Analysis Type:</Text>
              <Chip mode="outlined" compact>
                {analysisResult.type === 'video' ? '📹 Video' : '📸 Image'}
              </Chip>
            </View>
            <View style={styles.infoRow}>
              <Text style={styles.infoLabel}>Processing Time:</Text>
              <Text style={styles.infoValue}>
                {(analysisResult.processing_time / 1000).toFixed(1)}s
              </Text>
            </View>
            <View style={styles.infoRow}>
              <Text style={styles.infoLabel}>Analysis Date:</Text>
              <Text style={styles.infoValue}>
                {new Date(analysisResult.timestamp).toLocaleString()}
              </Text>
            </View>
          </Card.Content>
        </Card>
      </ScrollView>
    );
  };

  const renderCASATab = () => {
    const motility = analysisResult.motility_parameters;
    if (!motility) return null;

    const casaMetrics = [
      {
        name: 'VCL',
        fullName: 'Curvilinear Velocity',
        value: motility.average_vcl,
        unit: 'μm/s',
        description: 'Average velocity along the actual path',
        normalRange: '25-200',
      },
      {
        name: 'VSL',
        fullName: 'Straight Line Velocity',
        value: motility.average_vsl,
        unit: 'μm/s',
        description: 'Average velocity in straight line',
        normalRange: '25-150',
      },
      {
        name: 'VAP',
        fullName: 'Average Path Velocity',
        value: motility.average_vap,
        unit: 'μm/s',
        description: 'Average velocity along smoothed path',
        normalRange: '25-170',
      },
      {
        name: 'LIN',
        fullName: 'Linearity',
        value: motility.average_lin,
        unit: '%',
        description: 'Linearity of movement (VSL/VCL)',
        normalRange: '50-80',
      },
      {
        name: 'ALH',
        fullName: 'Amplitude Lateral Head',
        value: motility.average_alh,
        unit: 'μm',
        description: 'Amplitude of lateral head displacement',
        normalRange: '2-7',
      },
      {
        name: 'BCF',
        fullName: 'Beat Cross Frequency',
        value: motility.average_bcf,
        unit: 'Hz',
        description: 'Frequency of head crossing',
        normalRange: '5-45',
      },
    ];

    return (
      <ScrollView showsVerticalScrollIndicator={false}>
        <Text style={styles.tabDescription}>
          Computer Assisted Sperm Analysis (CASA) parameters provide detailed
          information about sperm movement characteristics.
        </Text>
        
        {casaMetrics.map((metric, index) => (
          <Card key={index} style={styles.casaCard}>
            <Card.Content>
              <View style={styles.casaHeader}>
                <Text style={styles.casaName}>{metric.name}</Text>
                <Text style={styles.casaValue}>
                  {metric.value.toFixed(1)} {metric.unit}
                </Text>
              </View>
              <Text style={styles.casaFullName}>{metric.fullName}</Text>
              <Text style={styles.casaDescription}>{metric.description}</Text>
              <View style={styles.casaRange}>
                <Text style={styles.casaRangeLabel}>Normal Range:</Text>
                <Text style={styles.casaRangeValue}>{metric.normalRange} {metric.unit}</Text>
              </View>
            </Card.Content>
          </Card>
        ))}
      </ScrollView>
    );
  };

  const renderChartsTab = () => {
    const motility = analysisResult.motility_parameters;
    if (!motility) return null;

    // Pie chart data for motility distribution
    const pieData = [
      {
        name: 'Progressive',
        population: motility.progressive_count,
        color: colors.success,
        legendFontColor: colors.text,
        legendFontSize: 12,
      },
      {
        name: 'Non-Progressive',
        population: motility.non_progressive_count,
        color: colors.warning,
        legendFontColor: colors.text,
        legendFontSize: 12,
      },
      {
        name: 'Immotile',
        population: motility.immotile_count,
        color: colors.error,
        legendFontColor: colors.text,
        legendFontSize: 12,
      },
    ];

    // Bar chart data for CASA metrics
    const barData = {
      labels: ['VCL', 'VSL', 'VAP', 'LIN', 'ALH', 'BCF'],
      datasets: [
        {
          data: [
            motility.average_vcl,
            motility.average_vsl,
            motility.average_vap,
            motility.average_lin,
            motility.average_alh,
            motility.average_bcf,
          ],
        },
      ],
    };

    const chartConfig = {
      backgroundColor: colors.surface,
      backgroundGradientFrom: colors.surface,
      backgroundGradientTo: colors.surface,
      decimalPlaces: 1,
      color: (opacity = 1) => `rgba(21, 101, 192, ${opacity})`,
      labelColor: (opacity = 1) => `rgba(33, 33, 33, ${opacity})`,
      style: {
        borderRadius: 16,
      },
      propsForDots: {
        r: '6',
        strokeWidth: '2',
        stroke: colors.primary,
      },
    };

    return (
      <ScrollView showsVerticalScrollIndicator={false}>
        {/* Motility Distribution */}
        <Card style={styles.chartCard}>
          <Card.Content>
            <Text style={styles.chartTitle}>Motility Distribution</Text>
            <PieChart
              data={pieData}
              width={chartWidth}
              height={220}
              chartConfig={chartConfig}
              accessor="population"
              backgroundColor="transparent"
              paddingLeft="15"
              center={[10, 50]}
              absolute
            />
          </Card.Content>
        </Card>

        {/* CASA Metrics Chart */}
        <Card style={styles.chartCard}>
          <Card.Content>
            <Text style={styles.chartTitle}>CASA Metrics</Text>
            <BarChart
              data={barData}
              width={chartWidth}
              height={220}
              chartConfig={chartConfig}
              verticalLabelRotation={30}
              yAxisLabel=""
              yAxisSuffix=""
              showValuesOnTopOfBars
            />
          </Card.Content>
        </Card>

        {/* Progress Indicators */}
        <Card style={styles.chartCard}>
          <Card.Content>
            <Text style={styles.chartTitle}>Quality Indicators</Text>
            <View style={styles.progressIndicators}>
              <View style={styles.progressItem}>
                <Text style={styles.progressLabel}>Motility</Text>
                <ProgressChart
                  data={{
                    data: [motility.motility_percentage / 100],
                  }}
                  width={80}
                  height={80}
                  strokeWidth={8}
                  radius={32}
                  chartConfig={{
                    ...chartConfig,
                    color: (opacity = 1) => colors.success,
                  }}
                  hideLegend
                />
                <Text style={styles.progressValue}>
                  {motility.motility_percentage.toFixed(1)}%
                </Text>
              </View>
              
              <View style={styles.progressItem}>
                <Text style={styles.progressLabel}>Progressive</Text>
                <ProgressChart
                  data={{
                    data: [motility.progressive_motility_percentage / 100],
                  }}
                  width={80}
                  height={80}
                  strokeWidth={8}
                  radius={32}
                  chartConfig={{
                    ...chartConfig,
                    color: (opacity = 1) => colors.info,
                  }}
                  hideLegend
                />
                <Text style={styles.progressValue}>
                  {motility.progressive_motility_percentage.toFixed(1)}%
                </Text>
              </View>
              
              <View style={styles.progressItem}>
                <Text style={styles.progressLabel}>Linearity</Text>
                <ProgressChart
                  data={{
                    data: [motility.average_lin / 100],
                  }}
                  width={80}
                  height={80}
                  strokeWidth={8}
                  radius={32}
                  chartConfig={{
                    ...chartConfig,
                    color: (opacity = 1) => colors.accent,
                  }}
                  hideLegend
                />
                <Text style={styles.progressValue}>
                  {motility.average_lin.toFixed(1)}%
                </Text>
              </View>
            </View>
          </Card.Content>
        </Card>
      </ScrollView>
    );
  };

  const tabs = [
    { key: 'overview', title: 'Overview', icon: 'dashboard' },
    { key: 'casa', title: 'CASA', icon: 'analytics' },
    { key: 'charts', title: 'Charts', icon: 'bar-chart' },
  ];

  return (
    <View style={styles.container}>
      {/* Header */}
      <Surface style={styles.header}>
        <Text style={styles.headerTitle}>📊 Analysis Results</Text>
        <View style={styles.headerActions}>
          <Button
            mode="outlined"
            onPress={shareResults}
            style={styles.headerButton}
            compact
          >
            Share
          </Button>
          <Button
            mode="contained"
            onPress={exportToPDF}
            style={styles.headerButton}
            compact
          >
            Export
          </Button>
        </View>
      </Surface>

      {/* Tabs */}
      <View style={styles.tabsContainer}>
        {tabs.map((tab) => (
          <Button
            key={tab.key}
            mode={selectedTab === tab.key ? 'contained' : 'outlined'}
            onPress={() => setSelectedTab(tab.key as any)}
            style={styles.tabButton}
            compact
          >
            {tab.title}
          </Button>
        ))}
      </View>

      {/* Content */}
      <View style={styles.content}>
        {selectedTab === 'overview' && renderOverviewTab()}
        {selectedTab === 'casa' && renderCASATab()}
        {selectedTab === 'charts' && renderChartsTab()}
      </View>
    </View>
  );
};

